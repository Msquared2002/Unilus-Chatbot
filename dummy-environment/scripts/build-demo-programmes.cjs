// Read the chatbot's existing ingested prospectus; write frontend assets only.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const sourceFile = 'backend/data/documents/chunks.json';
const document = 'UNILUS-PROSPECTUS-2026-11.pdf';

function extractProgrammes(chunks) {
  const sourceChunks = chunks.filter((chunk) => chunk.metadata.source_file === document && chunk.metadata.page_number === 7);
  const names = [];
  for (const line of sourceChunks.map((chunk) => chunk.text).join('\n').split('\n')) {
    const match = line.match(/^\d+\.\s+(.+)$/);
    if (match) names.push(match[1]);
    else if (line.trim() && !/^(Programmes on offer|School of |Bachelor’s Degree programmes)/.test(line)) {
      if (names.length) names[names.length - 1] += ` ${line.trim()}`;
    }
  }
  const programmes = names.map((name) => name.replace(/\s+/g, ' ').trim())
    .map((name) => ({ id: name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''), name }))
    .sort((a, b) => a.name.localeCompare(b.name, 'en'));
  if (programmes.length !== 85 || new Set(programmes.map((p) => p.id)).size !== programmes.length) {
    throw new Error('Prospectus programme index changed; review its numbered entries before regenerating.');
  }
  return { source: { file: sourceFile, document, pdfPage: 7, printedPage: 6,
    chunkIds: sourceChunks.map((chunk) => chunk.id) }, programmes };
}

if (require.main === module) {
  const catalogue = extractProgrammes(JSON.parse(fs.readFileSync(path.join(root, sourceFile), 'utf8')));
  const output = `// Generated by scripts/build-demo-programmes.cjs from the chatbot's local 2026 prospectus.\n(function (root) {\n  const catalogue = ${JSON.stringify(catalogue, null, 2)};\n  catalogue.programmes.forEach(Object.freeze);\n  Object.freeze(catalogue.programmes);\n  root.UnilusDemoProgrammes = catalogue;\n  if (typeof module !== "undefined") module.exports = catalogue;\n})(typeof window !== "undefined" ? window : globalThis);\n`;
  fs.writeFileSync(path.join(root, 'dummy-environment/js/demo-programmes.js'), output);
  require('../js/demo-programmes.js');
  const session = require('../js/demo-session.js');
  const wardrobe = require('../chatbot-widget/avatar-entitlements.js');
  const rows = catalogue.programmes.map((programme) => ({ ...programme,
    group: wardrobe.resolveProgramme(session.studentForProgramme(programme.id)) }));
  const report = [
    '# Demo programme wardrobe', '',
    'Login: `demo` / `unilus demo`. Select a Programme before signing in.', '',
    '## Local source audit', '',
    '- Canonical source: `backend/data/documents/chunks.json`, `UNILUS-PROSPECTUS-2026-11.pdf`, PDF page 7 (printed page 6), “Programmes on offer”.',
    '- The 2026 prospectus supplies 85 numbered entries: 23 undergraduate/diploma, 43 master’s, 16 doctoral and 3 postgraduate diploma programmes.',
    '- `backend/data/website/chunks.json` has a programmes index reporting 72 entries, but its ingested text omitted the names. Its individual Law, Computer Science and MBA pages agree with the prospectus.',
    '- Fee documents are programme/currency-specific subsets (including older 2025 schedules). Timetable records contain cohort/year/semester suffixes rather than a complete offering catalogue. The 2013 handbook is older.',
    '- Names below retain the prospectus spelling and capitalization; split lines are joined. No web research was required.', '',
    '## Specialist assignments', '',
    ...Object.keys(wardrobe.AVATAR_PROGRAMME_GROUPS).flatMap((group) => [
      `### ${group} (${rows.filter((p) => p.group === group).length})`, '',
      ...rows.filter((p) => p.group === group).map((p) => `- ${p.name}`), ''
    ]),
    `## General wardrobe only (${rows.filter((p) => !p.group).length})`, '',
    ...rows.filter((p) => !p.group).map((p) => `- ${p.name}`), '',
    '## Full alphabetical dropdown', '', '| Programme | Specialist group |', '|---|---|',
    ...rows.map((p) => `| ${p.name} | ${p.group || 'General wardrobe only'} |`), '',
    'Every authenticated programme also receives the general outfits and glasses. Only IT receives the independent laptop. Guest has a plain avatar and no customization controls.', '',
    'Preferences use the canonical programme ID internally. Programme changes take place through a fresh login, never through avatar settings.', ''
  ].join('\n');
  fs.writeFileSync(path.join(root, 'dummy-environment/PROGRAMME-WARDROBE.md'), report);
  console.log(`Generated ${catalogue.programmes.length} programmes from ${document}, PDF page 7.`);
}
module.exports = { extractProgrammes };
